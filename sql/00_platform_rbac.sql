-- Warehouse, cost guardrail, and least-privilege roles. Run as SYSADMIN / SECURITYADMIN.
-- Placeholders are filled by sf_cdc.render from config/dev.yaml.

CREATE WAREHOUSE IF NOT EXISTS {{warehouse}}
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

CREATE RESOURCE MONITOR IF NOT EXISTS {{warehouse}}_RM
  WITH CREDIT_QUOTA = {{monthly_credit_quota}} FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE {{warehouse}} SET RESOURCE_MONITOR = {{warehouse}}_RM;

CREATE DATABASE IF NOT EXISTS {{database}};
CREATE SCHEMA IF NOT EXISTS {{database}}.RAW;
CREATE SCHEMA IF NOT EXISTS {{database}}.CORE;

CREATE ROLE IF NOT EXISTS {{env}}_LOADER;       -- Snowpipe / COPY INTO only
CREATE ROLE IF NOT EXISTS {{env}}_TRANSFORMER;  -- streams, tasks, MERGE
CREATE ROLE IF NOT EXISTS {{env}}_ANALYST;      -- read CORE only

GRANT USAGE ON WAREHOUSE {{warehouse}} TO ROLE {{env}}_LOADER;
GRANT USAGE ON WAREHOUSE {{warehouse}} TO ROLE {{env}}_TRANSFORMER;
GRANT USAGE ON WAREHOUSE {{warehouse}} TO ROLE {{env}}_ANALYST;
GRANT USAGE ON DATABASE {{database}} TO ROLE {{env}}_LOADER;
GRANT USAGE ON DATABASE {{database}} TO ROLE {{env}}_TRANSFORMER;
GRANT USAGE ON DATABASE {{database}} TO ROLE {{env}}_ANALYST;

GRANT USAGE ON SCHEMA {{database}}.RAW TO ROLE {{env}}_LOADER;
GRANT INSERT, SELECT ON FUTURE TABLES IN SCHEMA {{database}}.RAW TO ROLE {{env}}_LOADER;

GRANT USAGE ON SCHEMA {{database}}.RAW TO ROLE {{env}}_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA {{database}}.RAW TO ROLE {{env}}_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW, CREATE STREAM, CREATE TASK ON SCHEMA {{database}}.CORE TO ROLE {{env}}_TRANSFORMER;

GRANT USAGE ON SCHEMA {{database}}.CORE TO ROLE {{env}}_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA {{database}}.CORE TO ROLE {{env}}_ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA {{database}}.CORE TO ROLE {{env}}_ANALYST;

GRANT ROLE {{env}}_LOADER TO ROLE {{env}}_TRANSFORMER;
